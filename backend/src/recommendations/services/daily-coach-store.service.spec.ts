import { ConflictException } from '@nestjs/common'
import knex, { Knex } from 'knex'
import { DailyCoachStore } from './daily-coach-store.service'

// Use Knex's real PostgreSQL compiler, replacing only the database transport.
function database() {
  const db = knex({ client: 'pg' })
  const responses: unknown[] = []
  const queries: { sql: string; bindings: readonly unknown[] }[] = []
  db.client.runner = (builder: Knex.QueryBuilder) => ({
    run: async () => {
      queries.push(builder.toSQL())
      const response = responses.shift()
      if (response instanceof Error) throw response
      return response
    },
  })
  const transaction = jest.fn(async (work: (trx: Knex) => Promise<unknown>) => work(db))
  Object.defineProperty(db, 'transaction', { value: transaction, configurable: true })
  return { db, responses, queries, transaction }
}

describe('DailyCoachStore', () => {
  it('reconcile un resultat persiste sans preparer une nouvelle generation', async () => {
    const { db, responses, transaction } = database()
    const result = { schedule: { id: 'old' } }
    responses.push([], [], { result })
    const prepare = jest.fn()
    const replay = jest.fn(async (trx: Knex.Transaction, cached: typeof result) => {
      expect(trx).toBe(db)
      expect(cached).toEqual(result)
      return { schedule: { id: 'current' } }
    })
    await expect(new DailyCoachStore(db).run('u', '2026-10-06', 'session', prepare, replay)).resolves.toEqual({
      schedule: { id: 'current' },
    })
    expect(prepare).not.toHaveBeenCalled()
    expect(transaction).toHaveBeenCalledTimes(1)
    await db.destroy()
  })

  it('ne prépare pas une seconde génération pendant que le détenteur du claim travaille', async () => {
    const { db, responses, queries } = database()
    responses.push([], [{}])
    let resume!: () => void
    let started!: () => void
    const entered = new Promise<void>(resolve => {
      started = resolve
    })
    const blocked = new Promise<void>(resolve => {
      resume = resolve
    })
    const store = new DailyCoachStore(db)
    const first = store.run('u', '2026-10-06', 'session', async () => {
      started()
      await blocked
      return async () => ({ generated: true })
    })
    await entered
    const token = queries[1].bindings[0]
    responses.push([], [], { result: null })
    const secondPrepare = jest.fn()
    await expect(new DailyCoachStore(db).run('u', '2026-10-06', 'session', secondPrepare)).rejects.toBeInstanceOf(
      ConflictException
    )
    expect(secondPrepare).not.toHaveBeenCalled()
    responses.push({ claim_id: token }, 1)
    resume()
    await expect(first).resolves.toEqual({ generated: true })
    await db.destroy()
  })

  it('propage une erreur de planification hors de la transaction sans enregistrer de succès', async () => {
    const { db, responses, queries, transaction } = database()
    responses.push([], [{}])
    const store = new DailyCoachStore(db)
    await expect(
      store.run('u', '2026-10-06', 'session', async () => {
        responses.push({ claim_id: queries[1].bindings[0] }, 1)
        return async () => {
          throw new Error('Schedule conflict')
        }
      })
    ).rejects.toThrow('Schedule conflict')
    expect(transaction).toHaveBeenCalledTimes(1)
    expect(queries.filter(query => query.sql.includes('"result" ='))).toHaveLength(0)
    await db.destroy()
  })

  it('réutilise une décision persistée après redémarrage sans préparer de génération', async () => {
    const { db, responses } = database()
    const result = { reason: 'rest_recommended' }
    responses.push([], [], { result }, [], [], { result })
    const prepare = jest.fn()
    expect(await new DailyCoachStore(db).run('u', '2026-10-06', 'session', prepare)).toEqual(result)
    expect(await new DailyCoachStore(db).run('u', '2026-10-06', 'session', prepare)).toEqual(result)
    expect(prepare).not.toHaveBeenCalled()
    await db.destroy()
  })

  it('réserve atomiquement avec plafond, bail et délai distincts', async () => {
    const { db, responses, queries } = database()
    responses.push([], [], { result: null })
    const prepare = jest.fn()
    await expect(new DailyCoachStore(db).run('u', '2026-10-06', 'session', prepare)).rejects.toBeInstanceOf(
      ConflictException
    )
    expect(queries[0].sql).toContain('on conflict ("user_id", "day", "operation") do nothing')
    expect(queries[1].sql).toContain('"attempts" < ?')
    expect(queries[1].bindings).toContain(3)
    expect(queries[1].sql).toContain('"retry_at" <= CURRENT_TIMESTAMP')
    expect(queries[1].sql).toContain('"lease_until" <= CURRENT_TIMESTAMP')
    expect(prepare).not.toHaveBeenCalled()
    await db.destroy()
  })

  it('enregistre le résultat dans la même transaction que les écritures métier', async () => {
    const { db, responses, queries, transaction } = database()
    responses.push([], [{ claim_id: 'unused' }])
    // The claim token is generated by the store; return it on the locked read.
    const prepare = jest.fn(async () => {
      const claimId = queries[1].bindings[0]
      responses.push({ claim_id: claimId }, 1)
      return async (trx: Knex.Transaction) => {
        expect(trx).toBe(db)
        return { generated: true }
      }
    })
    expect(await new DailyCoachStore(db).run('u', '2026-10-06', 'session', prepare)).toEqual({ generated: true })
    expect(transaction).toHaveBeenCalledTimes(1)
    expect(queries[2].sql).toContain('for update')
    expect(queries[3].bindings).toContain('{"generated":true}')
    await db.destroy()
  })

  it('bloque un ancien worker remplacé avant toute écriture métier', async () => {
    const { db, responses } = database()
    responses.push([], [{}], { claim_id: 'new-worker' }, 1)
    const finish = jest.fn()
    await expect(new DailyCoachStore(db).run('u', '2026-10-06', 'session', async () => finish)).rejects.toBeInstanceOf(
      ConflictException
    )
    expect(finish).not.toHaveBeenCalled()
    await db.destroy()
  })

  it('garde la tentative après échec et retarde le prochain essai de dix minutes', async () => {
    const { db, responses, queries } = database()
    responses.push([], [{}], 1)
    await expect(
      new DailyCoachStore(db).run('u', '2026-10-06', 'session', async () => {
        throw new Error('AI unavailable')
      })
    ).rejects.toThrow('AI unavailable')
    expect(queries[2].sql).toContain('"retry_at" = CURRENT_TIMESTAMP + INTERVAL \'10 minutes\'')
    expect(queries[2].sql).not.toContain('"attempts" =')
    expect(queries[2].sql).toContain('"claim_id" = ?')
    await db.destroy()
  })

  it('utilise une clé différente le lendemain et pour un autre utilisateur', async () => {
    const { db, responses, queries } = database()
    responses.push([], [], { result: 'rest' }, [], [], { result: 'work' })
    const store = new DailyCoachStore(db)
    await store.run('u', '2026-10-06', 'session', jest.fn())
    await store.run('other', '2026-10-07', 'session', jest.fn())
    expect(queries[0].bindings).toEqual(expect.arrayContaining(['u', '2026-10-06']))
    expect(queries[3].bindings).toEqual(expect.arrayContaining(['other', '2026-10-07']))
    await db.destroy()
  })
})
